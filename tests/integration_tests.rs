/// Turning an option off drops the port it pulled in, and everything only that
/// port pulled in, all the way down.
#[test]
fn test_disabling_an_option_strands_its_whole_subtree() {
    let mut tree = dep_graph_db(
        &[("www/app", "LUA", "lang/lua54")],
        &[("lang/lua54", "devel/readline"), ("www/app", "devel/pcre2")],
    );
    let sys_opts = SystemOptions::default();
    let mut graph = tree
        .build(&["www/app".to_string()], &sys_opts, false)
        .unwrap();

    // LUA defaults on, so the whole chain is pulled in
    assert_eq!(
        listed_origins(&graph),
        vec!["devel/pcre2", "devel/readline", "lang/lua54", "www/app"]
    );

    let row = find_option_row(&graph, "www/app", "LUA");
    graph.toggle_option(row);

    // lang/lua54 goes, and devel/readline goes with it; devel/pcre2 stays
    // because www/app requires it unconditionally
    assert_eq!(listed_origins(&graph), vec!["devel/pcre2", "www/app"]);
    assert!(!graph.is_live("lang/lua54"));
    assert!(!graph.is_live("devel/readline"));

    // Turning it back on restores the whole chain
    let row = find_option_row(&graph, "www/app", "LUA");
    graph.toggle_option(row);
    assert_eq!(
        listed_origins(&graph),
        vec!["devel/pcre2", "devel/readline", "lang/lua54", "www/app"]
    );
}

