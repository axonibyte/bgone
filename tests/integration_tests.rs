#[test]
fn test_exporter_writes_valid_options_files() {
    let temp = TempDir::new("exporter_write");
    let options_dir = temp.path.join("ports");
    let make_conf_path = temp.path.join("make.conf");

    // Set up database and graph
    let mut tree = common::Tree::new("t");

    tree.add_option("www/apache24", "HTTP2", true, "Enable HTTP2", "DEFINE", "");
    tree.add_option("www/apache24", "DOCS", false, "Build Docs", "DEFINE", "");
    tree.set_pkgname("www/apache24", "apache-2.4.58");

    let sys_opts = SystemOptions::default();
    let graph = tree
        .build(&["www/apache24".to_string()], &sys_opts, false)
        .unwrap();

    // Export options
    let stats =
        exporter::export_options(&graph, &options_dir, false, Some(&make_conf_path)).unwrap();

    assert_eq!(stats.files_written, 1);
    assert_eq!(stats.options_saved, 2);

    // Validate generated /var/db/ports/www_apache24/options file content
    let exported_file = options_dir.join("www_apache24").join("options");
    assert!(exported_file.exists());

    let content = fs::read_to_string(&exported_file).unwrap();
    assert!(content.contains("# This file is auto-generated by bgone."));
    assert!(content.contains("_OPTIONS_READ=apache-2.4.58"));
    // Every defined option must be listed, or config-conditional re-prompts
    assert!(content.contains("_FILE_COMPLETE_OPTIONS_LIST=DOCS HTTP2"));
    assert!(content.contains("OPTIONS_FILE_SET+=HTTP2"));
    assert!(content.contains("OPTIONS_FILE_UNSET+=DOCS"));

    // Validate generated make.conf file content
    assert!(make_conf_path.exists());
    let make_content = fs::read_to_string(&make_conf_path).unwrap();
    assert!(make_content.contains("OPTIONS_SET+=HTTP2"));
    assert!(make_content.contains("OPTIONS_UNSET+=DOCS"));
}

/// `PKGNAME` is whatever make reported, verbatim.
///
/// It used to be stitched together from PORTNAME and PORTVERSION whenever the
/// tree had not been read, which was wrong for 88% of ports — no PORTREVISION,
/// no PORTEPOCH, and no USES-synthesised prefix — and needed a rule for hiding
/// the placeholder version that produced. Nothing is reconstructed now, so the
/// only thing left to check is that the header says what the cache holds.
#[test]
fn test_exporter_writes_the_package_name_make_reported() {
    let temp = TempDir::new("exporter_versions");
    let options_dir = temp.path.join("ports");

    let mut tree = common::Tree::new("t");

    for (origin, opt, pkgname) in [
        // The forms a reconstruction could not produce: a revision, an epoch,
        // and a USES-synthesised prefix.
        ("www/nginx", "HTTPV3", "nginx-1.30.4_1,3"),
        ("devel/py-black", "STATIC", "py312-black-26.5.1"),
        ("www/known", "DOCS", "known-1.2.3"),
    ] {
        tree.add_option(origin, opt, false, "", "DEFINE", "");
        tree.set_pkgname(origin, pkgname);
    }

    let sys_opts = SystemOptions::default();
    let patterns = vec![
        "www/nginx".to_string(),
        "devel/py-black".to_string(),
        "www/known".to_string(),
    ];
    let graph = tree.build(&patterns, &sys_opts, false).unwrap();
    exporter::export_options(&graph, &options_dir, false, None).unwrap();

    let read = |port: &str| fs::read_to_string(options_dir.join(port).join("options")).unwrap();

    assert!(read("www_nginx").contains("_OPTIONS_READ=nginx-1.30.4_1,3\n"));
    assert!(read("devel_py-black").contains("_OPTIONS_READ=py312-black-26.5.1\n"));
    assert!(read("www_known").contains("_OPTIONS_READ=known-1.2.3\n"));
}

/// An option name that means different things to different ports is left out of
/// the global snippet rather than written both ways.
///
/// Deduping on `(name, enabled)` used to emit `OPTIONS_SET+=DOCS` *and*
/// `OPTIONS_UNSET+=DOCS` whenever two ports disagreed, leaving the outcome to
/// whichever `bsd.options.mk` applied last. The per-port files already say
/// exactly what each port wants, so the ambiguous name is simply omitted.
#[test]
fn test_the_global_snippet_omits_options_the_ports_disagree_about() {
    let temp = TempDir::new("exporter_globals");
    let options_dir = temp.path.join("ports");
    let make_conf = temp.path.join("make.conf");

    let mut tree = common::Tree::new("t");

    // DOCS disagrees; SSL is on everywhere; NLS is off everywhere.
    tree.add_option("www/one", "DOCS", true, "", "DEFINE", "");
    tree.add_option("www/one", "SSL", true, "", "DEFINE", "");
    tree.add_option("www/one", "NLS", false, "", "DEFINE", "");
    tree.add_option("www/two", "DOCS", false, "", "DEFINE", "");
    tree.add_option("www/two", "SSL", true, "", "DEFINE", "");
    tree.add_option("www/two", "NLS", false, "", "DEFINE", "");

    let patterns = vec!["www/one".to_string(), "www/two".to_string()];
    let graph = tree
        .build(&patterns, &SystemOptions::default(), false)
        .unwrap();
    exporter::export_options(&graph, &options_dir, false, Some(&make_conf)).unwrap();

    let content = fs::read_to_string(&make_conf).unwrap();
    assert!(content.contains("OPTIONS_SET+=SSL"));
    assert!(content.contains("OPTIONS_UNSET+=NLS"));
    assert!(
        !content.contains("DOCS"),
        "the ports disagree about DOCS, so it must not be stated globally either way:\n{content}"
    );

    // The per-port files still say exactly what each port wants
    let read = |p: &str| fs::read_to_string(options_dir.join(p).join("options")).unwrap();
    assert!(read("www_one").contains("OPTIONS_FILE_SET+=DOCS"));
    assert!(read("www_two").contains("OPTIONS_FILE_UNSET+=DOCS"));
}

/// Pointing --make-conf at a real, hand-maintained make.conf must be safe:
/// only the managed block is bgone's to rewrite. Overwriting the whole file
/// used to destroy CFLAGS, MAKE_JOBS_NUMBER — everything the user kept there.
#[test]
fn the_make_conf_block_preserves_the_users_file() {
    let temp = TempDir::new("exporter_managed_block");
    let options_dir = temp.path.join("ports");
    let make_conf = temp.path.join("make.conf");

    fs::write(
        &make_conf,
        "# my build settings\nCFLAGS+=-O2 -pipe\nMAKE_JOBS_NUMBER=4\n",
    )
    .unwrap();

    let mut tree = common::Tree::new("t");
    tree.add_option("www/one", "SSL", true, "", "DEFINE", "");
    tree.add_option("www/one", "NLS", false, "", "DEFINE", "");
    let graph = tree
        .build(&["www/one".to_string()], &SystemOptions::default(), false)
        .unwrap();

    // Exported twice: the second run has to replace its own block, not stack
    // another, and must leave the user's lines byte-identical both times.
    exporter::export_options(&graph, &options_dir, false, Some(&make_conf)).unwrap();
    exporter::export_options(&graph, &options_dir, false, Some(&make_conf)).unwrap();

    let content = fs::read_to_string(&make_conf).unwrap();
    assert!(content.contains("# my build settings"));
    assert!(content.contains("CFLAGS+=-O2 -pipe"));
    assert!(content.contains("MAKE_JOBS_NUMBER=4"));
    assert!(content.contains("OPTIONS_SET+=SSL"));
    assert!(content.contains("OPTIONS_UNSET+=NLS"));
    assert_eq!(
        content.matches("# BEGIN bgone").count(),
        1,
        "repeated exports must replace the block, not accumulate:\n{content}"
    );

    // ...and what was written still reads back as the same overrides.
    let reloaded = SystemOptions::load(&options_dir, Some(&make_conf)).unwrap();
    assert!(reloaded.get_state("dns/other", "SSL", false));
    assert!(!reloaded.get_state("dns/other", "NLS", true));
}

/// What the exporter writes must be what the reader reads back, otherwise a
/// second run silently discards the previous session's choices.
#[test]
fn test_exported_options_round_trip_through_the_reader() {
    let temp = TempDir::new("exporter_roundtrip");
    let options_dir = temp.path.join("ports");

    let mut tree = common::Tree::new("t");

    tree.add_port("www/apache24");
    tree.add_option("www/apache24", "HTTP2", true, "Enable HTTP2", "DEFINE", "");
    tree.add_option("www/apache24", "DOCS", false, "Build Docs", "DEFINE", "");

    let sys_opts = SystemOptions::default();
    let graph = tree
        .build(&["www/apache24".to_string()], &sys_opts, false)
        .unwrap();
    exporter::export_options(&graph, &options_dir, false, None).unwrap();

    // Defaults inverted, so anything not genuinely read back flips state
    let reloaded = SystemOptions::load(&options_dir, None).unwrap();
    assert!(reloaded.get_state("www/apache24", "HTTP2", false));
    assert!(!reloaded.get_state("www/apache24", "DOCS", true));

    let regraph = tree
        .build(&["www/apache24".to_string()], &reloaded, false)
        .unwrap();
    assert!(!regraph.is_dirty());
}

