fn test_graph_search_filtering() {
    let conn = Connection::open_in_memory().unwrap();
    db::init_db(&conn, true).unwrap();

    conn.execute(
        "INSERT INTO ports (origin, name, version, comment) VALUES ('net/curl', 'curl', '8.0', 'Data transfer tool')",
        [],
    ).unwrap();

    conn.execute(
        "INSERT INTO options (port_origin, option_name, default_state, description, group_type, group_name)
         VALUES ('net/curl', 'HTTP2', 1, 'Enable HTTP2 support', 'DEFINE', ''),
                ('net/curl', 'OPENSSL', 1, 'Use OpenSSL backend', 'DEFINE', ''),
                ('net/curl', 'COOKIES', 0, 'Enable Cookie support', 'DEFINE', '')",
        [],
    ).unwrap();

    let sys_opts = SystemOptions::default();
    let mut graph =
        DependencyGraph::load_from_db(&conn, &["net/curl".to_string()], &sys_opts, false).unwrap();

    // Expand all nodes
    graph.expand_all();
    let total_unfiltered_rows = graph.visible_rows.len();

    // Filter for "SSL"
    graph.search_query = "SSL".to_string();
    graph.rebuild_visible_rows();

    assert!(graph.visible_rows.len() < total_unfiltered_rows);
    assert!(graph.visible_rows.iter().any(|r| match &r.kind {
        RowKind::Option { name, .. } => name == "OPENSSL",
        _ => false,
    }));

    // Clear search filter
    graph.search_query.clear();
    graph.rebuild_visible_rows();
    assert_eq!(graph.visible_rows.len(), total_unfiltered_rows);
}

