#[test]
fn test_graph_radio_group_mutual_exclusion() {
    let conn = Connection::open_in_memory().unwrap();
    db::init_db(&conn, true).unwrap();

    conn.execute(
        "INSERT INTO ports (origin, name, version, comment) VALUES ('databases/db', 'db', '1.0', 'Database')",
        [],
    ).unwrap();

    // Insert two options in the same SINGLE group
    conn.execute(
        "INSERT INTO options (port_origin, option_name, default_state, description, group_type, group_name)
         VALUES ('databases/db', 'ENGINE_A', 1, 'Engine A', 'SINGLE', 'ENGINE'),
                ('databases/db', 'ENGINE_B', 0, 'Engine B', 'SINGLE', 'ENGINE')",
        [],
    ).unwrap();

    let sys_opts = SystemOptions::default();
    let mut graph =
        DependencyGraph::load_from_db(&conn, &["databases/db".to_string()], &sys_opts, false)
            .unwrap();

    // Verify initial states
    assert!(graph.option_nodes[0].enabled); // ENGINE_A
    assert!(!graph.option_nodes[1].enabled); // ENGINE_B

    // Row 0 is the root Port (already expanded by default).
    // Row 1 is ENGINE_A, Row 2 is ENGINE_B.
    // Toggle ENGINE_B at row 2 directly:
    graph.toggle_option(2);

    // Verify mutual exclusion: ENGINE_B becomes enabled, ENGINE_A becomes disabled
    assert!(!graph.option_nodes[0].enabled); // ENGINE_A disabled
    assert!(graph.option_nodes[1].enabled); // ENGINE_B enabled
}

