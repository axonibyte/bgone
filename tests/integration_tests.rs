#[test]
fn test_reader_precedence_and_parsing() {
    let temp = TempDir::new("reader");

    // Setup mock /var/db/ports/www_apache24/options
    let ports_dir = temp.path.join("ports");
    let apache_opts_dir = ports_dir.join("www_apache24");
    fs::create_dir_all(&apache_opts_dir).unwrap();
    fs::write(
        apache_opts_dir.join("options"),
        "# Mock options\n_OPTIONS_READ=apache24\nWITH_HTTP2=true\nWITHOUT_DOCS=true\n",
    )
    .unwrap();

    // Setup mock make.conf
    let make_conf = temp.path.join("make.conf");
    fs::write(
        &make_conf,
        "# Global options\nOPTIONS_SET+=GLOBAL_SET\nOPTIONS_UNSET+=GLOBAL_UNSET\n",
    )
    .unwrap();

    let sys_opts = SystemOptions::load(&ports_dir, Some(&make_conf));

    // 1. Per-port overrides
    assert_eq!(sys_opts.get_state("www/apache24", "HTTP2", false), true);
    assert_eq!(sys_opts.get_state("www/apache24", "DOCS", true), false);

    // 2. Global make.conf overrides
    assert_eq!(sys_opts.get_state("dns/bind9", "GLOBAL_SET", false), true);
    assert_eq!(sys_opts.get_state("dns/bind9", "GLOBAL_UNSET", true), false);

    // 3. Fallback to Makefile defaults when no override exists
    assert_eq!(
        sys_opts.get_state("www/apache24", "UNTOUCHED_OPT", true),
        true
    );
    assert_eq!(
        sys_opts.get_state("www/apache24", "UNTOUCHED_OPT", false),
        false
    );
}

