#[test]
fn test_exporter_writes_valid_options_files() {
    let temp = TempDir::new("exporter_write");
    let options_dir = temp.path.join("ports");
    let make_conf_path = temp.path.join("make.conf");

    // Set up database and graph
    let conn = Connection::open_in_memory().unwrap();
    db::init_db(&conn, true).unwrap();

    conn.execute(
        "INSERT INTO ports (origin, name, version, comment) VALUES ('www/apache24', 'apache', '2.4.58', 'Web Server')",
        [],
    ).unwrap();
    conn.execute(
        "INSERT INTO options (port_origin, option_name, default_state, description, group_type, group_name)
         VALUES ('www/apache24', 'HTTP2', 1, 'Enable HTTP2', 'DEFINE', ''),
                ('www/apache24', 'DOCS', 0, 'Build Docs', 'DEFINE', '')",
        [],
    ).unwrap();

    let sys_opts = SystemOptions::default();
    let graph =
        DependencyGraph::load_from_db(&conn, &["www/apache24".to_string()], &sys_opts, false)
            .unwrap();

    // Export options
    let stats =
        exporter::export_options(&graph, &options_dir, false, Some(&make_conf_path)).unwrap();

    assert_eq!(stats.files_written, 1);
    assert_eq!(stats.options_saved, 2);

    // Validate generated /var/db/ports/www_apache24/options file content
    let exported_file = options_dir.join("www_apache24").join("options");
    assert!(exported_file.exists());

    let content = fs::read_to_string(&exported_file).unwrap();
    assert!(content.contains("# Generated by bgone"));
    assert!(content.contains("_OPTIONS_READ=apache24"));
    assert!(content.contains("WITH_HTTP2=true"));
    assert!(content.contains("WITHOUT_DOCS=true"));

    // Validate generated make.conf file content
    assert!(make_conf_path.exists());
    let make_content = fs::read_to_string(&make_conf_path).unwrap();
    assert!(make_content.contains("OPTIONS_SET+=HTTP2"));
    assert!(make_content.contains("OPTIONS_UNSET+=DOCS"));
}

