/// The memo is keyed on the whole question, so a hit is never a guess.
#[test]
fn a_remembered_reply_is_not_asked_for_again() {
    let mut tree = common::Tree::new("oracle_memo");
    tree.add_option("www/nginx", "HTTP2", true, "Enable HTTP2", "DEFINE", "");
    tree.add_port_dep("www/nginx", "devel/pcre2");

    let oracle = tree.oracle();
    let first = oracle
        .facts("www/nginx", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(first.options.len(), 1);

    // Take the tree away. The answer is remembered, so it still comes back.
    fs::remove_file(tree.root().join("www/nginx/.port")).unwrap();
    let second = oracle
        .facts("www/nginx", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(second, first, "the reply must come from the memo");
}

/// A successful evaluation is the answer; failing to memoise it only costs the
/// next asker a re-evaluation. A busy or read-only cache used to turn a port
/// make had just described perfectly well into "could not be read".
#[test]
fn a_cache_that_cannot_be_written_does_not_fail_the_evaluation() {
    let mut tree = common::Tree::new("oracle_readonly_cache");
    tree.add_option("www/app", "ALPHA", true, "", "DEFINE", "");

    let oracle = tree.oracle();
    // Break the memo's table out from under the oracle: the cheapest
    // deterministic stand-in for a write that fails mid-session.
    let conn = rusqlite::Connection::open(tree.db_path()).unwrap();
    conn.execute_batch("DROP TABLE reply;").unwrap();
    drop(conn);

    let facts = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .expect("the evaluation succeeded; the failed memo write must not undo it");
    assert_eq!(facts.options.len(), 1);
}

/// The Makefile's age is part of the key, so a tree update simply misses.
#[test]
fn a_changed_makefile_is_evaluated_again() {
    let mut tree = common::Tree::new("oracle_mtime");
    tree.add_option("www/app", "ALPHA", true, "", "DEFINE", "");

    let oracle = tree.oracle();
    let before = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(before.options.len(), 1);

    // A new option, and a Makefile that says the port has moved on
    tree.add_option("www/app", "BETA", false, "", "DEFINE", "");
    let oracle = tree.oracle();
    let makefile = tree.root().join("www/app/Makefile");
    let later = std::time::SystemTime::now() + std::time::Duration::from_secs(120);
    let handle = fs::File::options().write(true).open(&makefile).unwrap();
    handle
        .set_times(fs::FileTimes::new().set_modified(later))
        .unwrap();

    let after = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(
        after.options.len(),
        2,
        "an older answer must not survive the Makefile changing"
    );
}

/// `Mk/` decides what any port evaluates to, so a framework update has to miss
/// the memo even though no port's own Makefile moved — a tree update that
/// touches only the framework used to serve stale replies forever.
#[test]
fn a_framework_change_is_evaluated_again() {
    let mut tree = common::Tree::new("oracle_framework_mtime");
    tree.add_option("www/app", "ALPHA", true, "", "DEFINE", "");

    let oracle = tree.oracle();
    let before = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(before.options.len(), 1);

    // The port grows an option without its own Makefile moving; only the
    // framework's age says anything changed.
    fs::write(
        tree.root().join("www/app/.port"),
        "pkgname\tapp-1.0\nopt\tALPHA\t1\tDEFINE\t\t\nopt\tBETA\t0\tDEFINE\t\t\n",
    )
    .unwrap();
    let later = std::time::SystemTime::now() + std::time::Duration::from_secs(120);
    let handle = fs::File::options()
        .write(true)
        .open(tree.root().join("Mk/bsd.port.mk"))
        .unwrap();
    handle
        .set_times(fs::FileTimes::new().set_modified(later))
        .unwrap();

    // A fresh oracle, as a new session after a tree update would build one.
    let oracle = tree.oracle();
    let after = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(
        after.options.len(),
        2,
        "an older answer must not survive the framework changing"
    );
}

/// With nothing changed, a second session answers from the memo. Guards two
/// regressions at once: the fixture bumping `Mk/`'s age on every rebuild, and
/// the write path storing rows under an unfolded age no later read computes.
#[test]
fn an_unchanged_tree_still_hits_the_memo_across_sessions() {
    let mut tree = common::Tree::new("oracle_framework_hit");
    tree.add_option("www/app", "ALPHA", true, "", "DEFINE", "");
    tree.write_out();

    // Age the framework ahead of the port, so the folded age differs from the
    // port's own — the shape that catches a row written unfolded.
    let later = std::time::SystemTime::now() + std::time::Duration::from_secs(120);
    let handle = fs::File::options()
        .write(true)
        .open(tree.root().join("Mk/bsd.port.mk"))
        .unwrap();
    handle
        .set_times(fs::FileTimes::new().set_modified(later))
        .unwrap();

    let oracle = tree.oracle();
    let before = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .unwrap();

    // Take the port description away: a re-evaluation would now fail, so a
    // successful answer can only be a memo hit.
    fs::remove_file(tree.root().join("www/app/.port")).unwrap();

    let oracle = tree.oracle();
    let after = oracle
        .facts("www/app", &bgone::oracle::Options::AsShipped)
        .unwrap();
    assert_eq!(
        after, before,
        "the second session must answer from the memo"
    );
}

